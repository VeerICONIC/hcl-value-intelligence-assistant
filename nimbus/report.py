"""Weekly executive report (FR-09): deterministic Markdown, every figure from the scorecard, every statement cited."""

from __future__ import annotations

from datetime import datetime

from nimbus.charters import CharterIndex, strip_injection
from nimbus.pipeline import PipelineResult, fmt_metric

COLS = ["adoption", "wau_change", "roi", "avg_monthly_benefit", "payback_months", "run_rate_vs_plan"]


def weekly_report(r: PipelineResult, index: CharterIndex | None = None) -> str:
    sc = r.scorecard
    counts = sc.status.value_counts().to_dict()
    lines = [
        "# Nimbus Group AI Portfolio: Weekly Executive Report",
        "",
        f"Reporting week ending **{r.as_of.isoformat()}** · data version `{r.data_version}` · generated {datetime.now():%Y-%m-%d %H:%M}",
        "",
        "All figures are produced by the governed scorecard code; narrative evidence is quoted from initiative charters. "
        "No figure in this report was generated by a language model.",
        "",
        "## Portfolio summary",
        "",
        f"- Initiatives tracked: **{len(sc)}**",
        f"- Green: **{counts.get('Green', 0)}** · Amber: **{counts.get('Amber', 0)}** · Red: **{counts.get('Red', 0)}**"
        + (f" · Insufficient data: **{counts['Insufficient data']}**" if counts.get("Insufficient data") else ""),
        "",
        "## Initiatives requiring attention",
        "",
    ]
    footnotes, n = [], 0
    attention = sc[sc.status.isin(["Red", "Amber", "Insufficient data"])].copy()
    order = {"Red": 0, "Insufficient data": 1, "Amber": 2}
    attention["_o"] = attention.status.map(order)
    for _, row in attention.sort_values(["_o", "roi"]).iterrows():
        n += 1
        lines.append(f"### {row['name']} ({row.initiative_id}): {row.status}")
        lines.append("")
        lines.append(f"- **Why:** {row.status_reason}. [^{n}]")
        footnotes.append(f"[^{n}]: Scorecard row {row.initiative_id}: adoption {fmt_metric('adoption', row.adoption)}, "
                         f"ROI {fmt_metric('roi', row.roi)}, run-rate vs plan {fmt_metric('run_rate_vs_plan', row.run_rate_vs_plan)} "
                         f"(data version {r.data_version}).")
        if index is not None:
            risks = index.section(row.initiative_id, "Risks and Mitigations")
            if risks:
                text = strip_injection(risks[0].text)[0].strip(" -")
                n += 1
                lines.append(f"- **Charter risks:** {text[:400]} [^{n}]")
                footnotes.append(f"[^{n}]: Charter {risks[0].source_file}, section Risks and Mitigations.")
            else:
                lines.append("- **Charter risks:** I do not have that in the data provided (the charter has no Risks section).")
        lines.append("")
    if attention.empty:
        lines += ["No initiative requires attention this week.", ""]
    lines += ["## Full scorecard", "",
              "| Initiative | Adoption | WAU change | ROI | Avg monthly benefit | Payback | Run-rate vs plan | Status |",
              "|---|---|---|---|---|---|---|---|"]
    for _, row in sc.sort_values("initiative_id").iterrows():
        vals = " | ".join(fmt_metric(c, row[c]) for c in COLS)
        lines.append(f"| {row['name']} ({row.initiative_id}) | {vals} | {row.status} |")
    lines += ["", "Status rule: Red if adoption < 30% or ROI < 0; otherwise Green if adoption ≥ 60% and ROI > 0; otherwise Amber.", "",
              "## Data quality this week", "",
              f"{len(r.changes)} corrections or flags were applied by the cleaning pipeline (see the change log). "
              "The scorecard uses only the cleaned data.", "", "## Sources", ""] + footnotes
    return "\n".join(lines)
